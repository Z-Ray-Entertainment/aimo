def main() -> None:
    entries = extract_msgids()
    for lang in SUPPORTED_LANGUAGES:
        po_path = LOCALES_DIR / lang / "LC_MESSAGES" / "messages.po"
        existing = parse_po(po_path)
        header = (
            'msgid ""\n'
            'msgstr ""\n'
            f'"Language: {lang}\\n"\n'
            '"Content-Type: text/plain; charset=UTF-8\\n"\n'
            '"Content-Transfer-Encoding: 8bit\\n"\n\n'
        )
        chunks = [header]
        for msgid, refs in entries.items():
            if lang == "en":
                translated = msgid
            elif lang == "de":
                translated = DE_TRANSLATIONS.get(msgid, existing.get(msgid, ""))
            else:
                translated = existing.get(msgid, "")
            ref_line = "#: " + " ".join(refs[:5]) + "\n"
            chunks.append(
                ref_line
                + _format_po_entry("msgid", msgid)
                + _format_po_entry("msgstr", translated)
                + "\n"
            )
        po_path.write_text("".join(chunks), encoding="utf-8")
    compile_all()
    print(f"DE coverage: {sum(1 for k in entries if DE_TRANSLATIONS.get(k))}/{len(entries)}")


if __name__ == "__main__":
    main()
